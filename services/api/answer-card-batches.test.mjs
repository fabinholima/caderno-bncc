import assert from 'node:assert/strict';
import test from 'node:test';
import {
  hasSeparateFinalAnswerCard,
  parsePdfPageCount,
  selectFinalAnswerCardPage,
} from './answer-card-batches.mjs';

test('identifies layouts that place the answer card on its own final page', () => {
  assert.equal(hasSeparateFinalAnswerCard('certo-errado-v1'), true);
  assert.equal(hasSeparateFinalAnswerCard('simulado-v1'), true);
  assert.equal(hasSeparateFinalAnswerCard(undefined), true);
  assert.equal(hasSeparateFinalAnswerCard('compacto-10-v1'), false);
});

test('selects the numerically last page generated by pdfseparate', () => {
  assert.equal(
    selectFinalAnswerCardPage(
      ['1-page-1.pdf', '1-page-10.pdf', '1-page-2.pdf', '2-page-1.pdf'],
      '1-page-',
    ),
    '1-page-10.pdf',
  );
  assert.equal(selectFinalAnswerCardPage(['unrelated.pdf'], '1-page-'), null);
});

test('reads the page count reported by pdfinfo', () => {
  assert.equal(parsePdfPageCount('Title: prova\nPages:          12\n'), 12);
  assert.equal(parsePdfPageCount('Pages: 0\n'), null);
  assert.equal(parsePdfPageCount('PDF inválido'), null);
});
